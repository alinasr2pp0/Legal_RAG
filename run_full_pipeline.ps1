# PowerShell script to run the complete Egyptian Civil Code RAG pipeline
# ---------------------------------------------------------------
# Usage:   .\run_full_pipeline.ps1
# Ensure you are in the project root (d:\Documents\egyptian-civil-code-rag)
# ---------------------------------------------------------------

# 1. Activate Python environment (if you use a virtualenv)
# Uncomment the line below if you have a venv named 'venv'
# .\venv\Scripts\Activate.ps1

# 2. Ensure required Python packages are installed
Write-Host "Installing Python dependencies..."
python -m pip install -r requirements.txt
python -m pip install rank-bm25

# 3. Load environment variables from .env
$envFile = "${PWD}\.env"
if (Test-Path $envFile) {
    Get-Content $envFile | ForEach-Object {
        if ($_ -match '^\s*([^#=]+)=([^#]*)') {
            $key = $matches[1].Trim()
            $value = $matches[2].Trim()
            Set-Item -Force -Path "Env:$key" -Value $value
        }
    }
    Write-Host "Loaded .env variables"
} else {
    Write-Warning ".env file not found – proceeding with defaults"
}

# 4. Download embedding and reranker models
Write-Host "Downloading models..."
$env:PYTHONPATH = "src"
python scripts\data\download_models.py

# 5. Chunk the cleaned articles (input is the cleaned JSON generated by the ingestion pipeline)
Write-Host "Chunking articles..."
python scripts\data\chunk_articles.py --input data\interim\articles_clean.json --output data\processed\chunks.json

# 6. Build the vector index (BM25 + dense) using the generated chunks
Write-Host "Building vector index..."
python scripts\data\build_index.py --input data\processed\chunks.json

# 7. Export serving data (copies chunks and articles to the serving folder and writes MANIFEST)
Write-Host "Exporting serving data..."
python scripts\data\export_serving_data.py

# 8. Launch the FastAPI server (daemonized – you can stop it later with CTRL+C or by killing the process)
Write-Host "Starting FastAPI server..."
uvicorn src.api.main:app --host 0.0.0.0 --port 8000

